#!/usr/bin/env node

// Progress logger for repo-refresh plugin
// Runs on PostToolUse for Write|Edit tools - captures actual file work
// Cross-platform (Windows/Mac/Linux)

const fs = require('fs');
const path = require('path');

const projectDir = process.env.CLAUDE_PROJECT_DIR || process.cwd();
const progressDir = path.join(projectDir, '.claude', 'progress');
const today = new Date().toISOString().split('T')[0];
const progressFile = path.join(progressDir, `${today}.md`);
const timestamp = new Date().toTimeString().split(' ')[0];

// Read stdin for hook input
let input = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', chunk => input += chunk);
process.stdin.on('end', () => {
  try {
    // Create progress directory if needed
    if (!fs.existsSync(progressDir)) {
      fs.mkdirSync(progressDir, { recursive: true });
    }

    // Parse hook input
    let data = {};
    try {
      data = JSON.parse(input);
    } catch (e) {
      process.exit(0);
    }

    const toolName = data.tool_name || 'unknown';
    const filePath = data.tool_input?.file_path || data.tool_input?.path || null;
    
    if (!filePath) process.exit(0);

    const fileName = path.basename(filePath);

    // Create today's log if it doesn't exist
    if (!fs.existsSync(progressFile)) {
      fs.writeFileSync(progressFile, `# Progress Log - ${today}\n\n_Auto-generated by repo-refresh plugin_\n\n---\n\n`);
    }

    // Append entry
    fs.appendFileSync(progressFile, `- \`${timestamp}\` **${toolName}** → \`${fileName}\`\n`);

  } catch (e) {
    // Fail silently
  }
  process.exit(0);
});
